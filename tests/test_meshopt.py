def _hex(name):
    f = _FIXTURES[name]
    return (bytes.fromhex(f['comp']), bytes.fromhex(f['data']), f)


def test_vertex_fixtures():
    for name in ('v40x16', 'v7x8', 'v258x4', 'v1x4'):
        comp, expect, f = _hex(name)
        got = meshopt.decode_vertex_buffer(f['count'], f['size'], comp)
        assert got == expect, f'{name} 输出不一致'
    print('  ok: 顶点流 4 组 bit-exact（40×16 / 7×8 / 258×4 双块 / 1×4 边界）')


def test_index_fixtures():
    for name in ('i486x4', 'i12x4', 'i12x2'):
        comp, expect, f = _hex(name)
        got = meshopt.decode_index_buffer(f['count'], f['size'], comp)
        assert got == expect, f'{name} 输出不一致'
    print('  ok: 索引流 3 组 bit-exact（486 网格 u32 / 12 索引 u32 / u16）')


def test_sequence_fixture():
    comp, expect, f = _hex('s12x2')
    got = meshopt.decode_index_sequence(f['count'], f['size'], comp)
    assert got == expect, '序列输出不一致'
    print('  ok: 索引序列 bit-exact（双基线 delta）')


def test_vertex_errors():
    # 坏 header
    for blob in (b'\x00' + b'\x00' * 40, b'\xe1' + b'\x00' * 40):
        try:
            meshopt.decode_vertex_buffer(1, 4, blob)
            raise AssertionError('坏 header 应报错')
        except MeshoptError:
            pass
    # 截断（尾部容纳不下）
    comp, _, f = _hex('v7x8')
    for cut in (2, 6):
        try:
            meshopt.decode_vertex_buffer(f['count'], f['size'], comp[:-cut])
            raise AssertionError(f'截断 {cut}B 应报错')
        except MeshoptError:
            pass
    # 非法通道类型（把通道字节低 2 位改成 3）
    comp, _, f = _hex('v258x4')
    bad = bytearray(comp)
    bad[-1] |= 3                      # vs=4 → 通道字节即最后一字节
    try:
        meshopt.decode_vertex_buffer(f['count'], f['size'], bytes(bad))
        raise AssertionError('非法通道类型应报错')
    except MeshoptError:
        pass
    # 非法步长
    try:
        meshopt.decode_vertex_buffer(1, 6, comp)
        raise AssertionError('步长非 4 倍数应报错')
    except MeshoptError:
        pass
    print('  ok: 顶点错误路径（坏 header / 截断 / 非法通道 / 步长）')


def test_index_errors():
    # 索引数非 3 倍数
    comp, _, f = _hex('i12x4')
    try:
        meshopt.decode_index_buffer(f['count'] + 1, 4, comp)
        raise AssertionError('非 3 倍数应报错')
    except MeshoptError:
        pass
    # 截断
    try:
        meshopt.decode_index_buffer(f['count'], 4, comp[:-5])
        raise AssertionError('截断应报错')
    except MeshoptError:
        pass
    # 坏 header
    try:
        meshopt.decode_index_buffer(3, 4, b'\xa1' + b'\x00' * 32)
        raise AssertionError('坏 header 应报错')
    except MeshoptError:
        pass
    # u16 输出与 u32 输出的低半部分一致
    comp, _, f = _hex('i12x2')
    u16 = meshopt.decode_index_buffer(f['count'], 2, comp)
    u32 = meshopt.decode_index_buffer(f['count'], 4, comp)
    import struct
    assert [struct.unpack_from('<H', u16, i * 2)[0] for i in range(12)] == \
        [struct.unpack_from('<I', u32, i * 4)[0] for i in range(12)]
    print('  ok: 索引错误路径（非 3 倍数 / 截断 / 坏 header）+ u16/u32 口径一致')



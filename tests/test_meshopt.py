    print('test_vertex_fixtures');   test_vertex_fixtures()
    print('test_index_fixtures');    test_index_fixtures()
    print('test_sequence_fixture');  test_sequence_fixture()
    print('test_vertex_errors');     test_vertex_errors()
    print('test_index_errors');      test_index_errors()
    print('ALL_MESHOPT_TESTS_PASSED')



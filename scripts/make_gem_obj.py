# -*- coding: utf-8 -*-
"""生成测试模型资产 assets/gem.obj（正八面体"宝石"）。

注意：pyglet 的 OBJ 解码器以系统默认编码（Windows=GBK）读取文件，
**内容必须保持纯 ASCII**——任何非 ASCII 字符（如中文注释、em 破折号）
都会触发 UnicodeDecodeError，且被包装成无消息的 ModelDecodeException。

资产为本脚本程序化生成（MIT，随本仓发布），非第三方素材——
借：无外部来源；记账：scripts/make_gem_obj.py 即出处。
用法：python scripts/make_gem_obj.py
"""
import math
import os

S_XZ = 0.9     # 赤道半径
S_Y = 1.15     # 顶点高度


def norm(v):
    l = math.sqrt(sum(c * c for c in v))
    return tuple(c / l for c in v)


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1],
            a[2] * b[0] - a[0] * b[2],
            a[0] * b[1] - a[1] * b[0])


def main():
    P = (S_XZ, 0, 0)
    N = (-S_XZ, 0, 0)
    T = (0, S_Y, 0)
    B = (0, -S_Y, 0)
    F = (0, 0, S_XZ)
    K = (0, 0, -S_XZ)
    verts = [P, N, T, B, F, K]
    faces = [(0, 2, 4), (0, 4, 3), (0, 3, 5), (0, 5, 2),
             (1, 4, 2), (1, 3, 4), (1, 5, 3), (1, 2, 5)]

    lines = ['# gem.obj - generated by scripts/make_gem_obj.py (MIT)']
    for v in verts:
        lines.append(f'v {v[0]:.4f} {v[1]:.4f} {v[2]:.4f}')
    for a, b, c in faces:
        # 面法线 = normalize(cross(B-A, C-A))
        e1 = tuple(verts[b][i] - verts[a][i] for i in range(3))
        e2 = tuple(verts[c][i] - verts[a][i] for i in range(3))
        n = norm(cross(e1, e2))
        lines.append(f'vn {n[0]:.4f} {n[1]:.4f} {n[2]:.4f}')
    for fi, (a, b, c) in enumerate(faces, start=1):
        lines.append(f'f {a+1}//{fi} {b+1}//{fi} {c+1}//{fi}')

    out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                       'assets', 'gem.obj')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    print('WROTE', out, f'({len(faces)} faces)')


if __name__ == '__main__':
    main()
